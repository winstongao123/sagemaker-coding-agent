_CHART_TYPES_V4 = (
    "bar", "grouped_bar", "stacked_bar", "line", "pie",
    "scatter", "horizontal_bar", "combo",
)


def _create_chart_executor(args: Dict[str, Any], context: Optional[Dict] = None) -> str:
    filepath = str(args.get("filepath") or args.get("file_path") or "").strip()
    chart_type = (args.get("chart_type") or "bar").lower()
    data = args.get("data")
    title = args.get("title") or ""
    xlabel = args.get("xlabel")
    ylabel = args.get("ylabel")
    colors = args.get("colors") or None
    dpi = args.get("dpi")
    width = args.get("width")
    height = args.get("height")
    style = args.get("style")
    # Codex iter-3 MEDIUM: v4 required `data`. Reject missing payload.
    if data is None:
        return "Error: data is required ({labels:[],values:[]} or {x:[],y:[]} or {labels:[],series:[{name,values}]})"
    # Codex iter-4 HIGH fix: v4 defaults filepath to "chart.png" when omitted
    # (sagemaker_agent.py:6049-6052; schema required=[data]).
    if not filepath:
        filepath = "chart.png"
    if not filepath.endswith(".png"):
        filepath += ".png"
    err, abs_path = _validate_doc_path(filepath)
    if err:
        return err
    try:
        import matplotlib
        matplotlib.use("Agg")  # non-interactive backend for SageMaker
        import matplotlib.pyplot as plt
    except ImportError:
        return "Error: matplotlib not installed; install via `pip install matplotlib`"
    try:
        if style:
            try:
                plt.style.use(str(style))
            except Exception:
                pass  # silently fall back to default style on bad name
        # Codex iter-1/3 HIGH: accept v4 shapes:
        # - {label: value} (v5 dict shape)
        # - {labels: [...], values: [...]} (v4 simple shape)
        # - {x: [...], y: [...]} (v4 scatter shape)
        # - {labels: [...], series: [{name, values}, ...]} (v4 grouped/stacked/combo)
        labels: List[Any] = []
        values: List[Any] = []
        x_vals: List[Any] = []
        y_vals: List[Any] = []
        series: List[Dict[str, Any]] = []
        if isinstance(data, dict):
            if "x" in data and "y" in data:
                x_vals = list(data.get("x") or [])
                y_vals = list(data.get("y") or [])
                labels = [str(x) for x in x_vals]
                values = list(y_vals)
            elif "labels" in data and "series" in data:
                labels = list(data.get("labels") or [])
                series_raw = data.get("series") or []
                series = [
                    {"name": str(s.get("name") or f"series{i}"),
                     "values": list(s.get("values") or [])}
                    for i, s in enumerate(series_raw) if isinstance(s, dict)
                ]
                if series:
                    values = series[0]["values"]
            elif "labels" in data and "values" in data:
                labels = list(data.get("labels") or [])
                values = list(data.get("values") or [])
            elif "labels" in data and ("bar_values" in data or "line_values" in data):
                # Codex iter-5 MEDIUM fix: v4 combo shape
                # {labels, bar_values, line_values, ...} must NOT fall through
                # to the generic dict-keys path (which would set labels =
                # ["labels", "bar_values", ...]). Set labels + values from
                # explicit fields; the combo branch later reads bar/line vals.
                labels = list(data.get("labels") or [])
                values = list(data.get("bar_values") or data.get("line_values") or [])
            else:
                labels = list(data.keys())
                values = list(data.values())
        fig_kwargs: Dict[str, Any] = {}
        if width and height:
            try:
                fig_kwargs["figsize"] = (float(width), float(height))
            except Exception:
                pass
        fig, ax = plt.subplots(**fig_kwargs)
        n_labels = len(labels)
        # Render based on chart type.
        if chart_type == "line":
            if series:
                for s in series:
                    ax.plot(labels[:len(s["values"])], s["values"], label=s["name"])
                ax.legend()
            else:
                ax.plot(labels, values, color=(colors[0] if colors else None))
        elif chart_type == "pie":
            ax.pie(values, labels=labels, colors=colors)
        elif chart_type == "scatter":
            ax.scatter(x_vals or labels, y_vals or values,
                       c=(colors[0] if colors else None))
        elif chart_type == "horizontal_bar":
            ax.barh(labels, values, color=colors)
        elif chart_type == "grouped_bar" and series:
            # Grouped bar: each series is one bar per label, offset within group.
            try:
                import numpy as np  # numpy ships with matplotlib
                x = np.arange(n_labels)
                width_per = 0.8 / max(1, len(series))
                for i, s in enumerate(series):
                    ax.bar(x + i * width_per, s["values"], width_per,
                           label=s["name"],
                           color=(colors[i] if colors and i < len(colors) else None))
                ax.set_xticks(x + width_per * (len(series) - 1) / 2)
                ax.set_xticklabels(labels)
                ax.legend()
            except Exception:
                ax.bar(labels, values, color=colors)
        elif chart_type == "stacked_bar" and series:
            try:
                bottom = [0.0] * n_labels
                for i, s in enumerate(series):
                    vals = list(s["values"]) + [0] * max(0, n_labels - len(s["values"]))
                    ax.bar(labels, vals[:n_labels], bottom=bottom, label=s["name"],
                           color=(colors[i] if colors and i < len(colors) else None))
                    bottom = [b + v for b, v in zip(bottom, vals[:n_labels])]
                ax.legend()
            except Exception:
                ax.bar(labels, values, color=colors)
        elif chart_type == "combo":
            # Codex iter-4 MEDIUM fix: v4 combo shape is
            # {labels, bar_values, line_values, bar_label, line_label, line_ylabel}
            # (sagemaker_agent.py:6194-6214). Support v4 shape first;
            # fall back to series-based combo if data uses {labels, series}.
            try:
                if isinstance(data, dict) and "bar_values" in data and "line_values" in data:
                    bar_values = list(data.get("bar_values") or [])
                    line_values = list(data.get("line_values") or [])
                    bar_label = str(data.get("bar_label") or "Bar")
                    line_label = str(data.get("line_label") or "Line")
                    line_ylabel = data.get("line_ylabel")
                    n = min(len(labels), len(bar_values))
                    ax.bar(labels[:n], bar_values[:n], label=bar_label,
                           color=(colors[0] if colors else None))
                    if line_ylabel:
                        ax2 = ax.twinx()
                        ax2.set_ylabel(str(line_ylabel))
                        ax2.plot(labels[:len(line_values)], line_values, label=line_label,
                                 color=(colors[1] if colors and len(colors) > 1 else "tab:orange"))
                        ax2.legend(loc="upper right")
                    else:
                        ax.plot(labels[:len(line_values)], line_values, label=line_label,
                                color=(colors[1] if colors and len(colors) > 1 else "tab:orange"))
                    ax.legend(loc="upper left")
                elif series:
                    # series-based combo: first series as bar, rest as line.
                    first = series[0]
                    ax.bar(labels[:len(first["values"])], first["values"], label=first["name"],
                           color=(colors[0] if colors else None))
                    for i, s in enumerate(series[1:], start=1):
                        ax.plot(labels[:len(s["values"])], s["values"], label=s["name"],
                                color=(colors[i] if colors and i < len(colors) else None))
                    ax.legend()
                else:
                    ax.bar(labels, values, color=colors)
            except Exception:
                ax.bar(labels, values, color=colors)
        else:  # bar (default + fallback)
            ax.bar(labels, values, color=colors)
        if title:
            ax.set_title(title)
        if xlabel:
            ax.set_xlabel(str(xlabel))
        if ylabel:
            ax.set_ylabel(str(ylabel))
        os.makedirs(os.path.dirname(abs_path) or ".", exist_ok=True)
        save_kwargs: Dict[str, Any] = {}
        if dpi:
            try:
                save_kwargs["dpi"] = int(dpi)
            except Exception:
                pass
        fig.savefig(abs_path, **save_kwargs)
        plt.close(fig)
        _record_created_artifact(abs_path, "create_chart", context)
        return f"Wrote {abs_path}"
    except Exception as exc:  # noqa: BLE001
        return f"Error: {type(exc).__name__}: {exc}"


