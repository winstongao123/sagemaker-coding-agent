def _create_notebook_executor(args: Dict[str, Any], context: Optional[Dict] = None) -> str:
    filepath = str(args.get("filepath") or args.get("file_path") or "").strip()
    cells = args.get("cells") or []
    if not filepath:
        return "Error: filepath is required"
    if not filepath.endswith(".ipynb"):
        filepath += ".ipynb"
    err = _ascii_contract_check(json.dumps(cells, ensure_ascii=False, default=str), context)
    if err:
        return err
    err, abs_path = _validate_doc_path(filepath)
    if err:
        return err
    try:
        nb_cells = []
        for c in cells:
            if isinstance(c, dict):
                cell_type = c.get("type", "code")
                source = c.get("source", "")
                if isinstance(source, str):
                    source_lines = source.splitlines(keepends=True)
                else:
                    source_lines = list(source) if isinstance(source, list) else [str(source)]
                cell = {
                    "cell_type": cell_type,
                    "metadata": {},
                    "source": source_lines,
                }
                if cell_type == "code":
                    cell["execution_count"] = None
                    cell["outputs"] = []
                nb_cells.append(cell)
            elif isinstance(c, str):
                nb_cells.append({
                    "cell_type": "code",
                    "metadata": {},
                    "source": c.splitlines(keepends=True),
                    "execution_count": None,
                    "outputs": [],
                })
        notebook = {
            "cells": nb_cells,
            "metadata": {
                "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                "language_info": {"name": "python", "version": "3.11"},
            },
            "nbformat": 4,
            "nbformat_minor": 5,
        }
        os.makedirs(os.path.dirname(abs_path) or ".", exist_ok=True)
        with open(abs_path, "w", encoding="utf-8") as f:
            json.dump(notebook, f, indent=2)
        _record_created_artifact(abs_path, "create_notebook", context)
        return f"Wrote {abs_path}"
    except Exception as exc:  # noqa: BLE001
        return f"Error: {type(exc).__name__}: {exc}"


